def main():
    out = {"uz": {}, "ru": {}, "en": {}}
    for k, v in T.items():
        assert len(v) == 3 and all(isinstance(x, str) and x.strip() for x in v), k
        # format placeholders must match across languages
        ph = [sorted(re.findall(r"%[-0-9.]*[sdf]", x)) for x in v]
        assert ph[0] == ph[1] == ph[2], f"placeholder mismatch in {k}: {ph}"
        out["uz"][k] = uz(v[0])
        out["ru"][k] = v[1]
        out["en"][k] = v[2]
    for lang, d in out.items():
        with open(os.path.join(OUT, lang + ".json"), "w", encoding="utf-8") as f:
            json.dump(d, f, ensure_ascii=False, indent=1, sort_keys=True)
    print("wrote", len(T), "keys x 3 languages")

if __name__ == "__main__":
    main()
